// Writes nodes/NuaSense/catalog.ts from the API's own OpenAPI model
// (node-back-end/src/nuasense/openapiSpec.js), so the node offers exactly the
// datasets and analyses the public spec offers: nothing withheld on licence
// grounds, no trade analyses, no alert routes.
//
//   node scripts/generate-catalog.cjs          write the file
//   node scripts/generate-catalog.cjs --check  exit 1 if the file is stale
//
// Runs inside the monorepo only; the published package carries the generated
// file and never reaches back into the backend.

const fs = require('fs');
const path = require('path');

const backend = path.resolve(__dirname, '../../../node-back-end/src/nuasense/openapiSpec');
const { operations } = require(backend);

const COMMON = new Set(['start', 'end', 'every', 'agg', 'fields', 'limit', 'order']);
const ops = operations();

const datasets = ops
	.filter((o) => o.base === '/api/nuasense/v1' && o.path !== '/catalog')
	.map((o) => ({
		path: o.path,
		title: o.summary,
		group: o.tag,
		description: o.description,
		filters: o.params.filter((p) => !COMMON.has(p.name)).map((p) => p.name),
	}))
	.sort((a, b) => (a.group === b.group ? a.title.localeCompare(b.title) : a.group.localeCompare(b.group)));

const analyses = ops
	.filter((o) => o.base !== '/api/nuasense/v1')
	.map((o) => ({ path: o.path, question: o.summary, params: o.params.map((p) => p.name) }));

const out = `// Generated by scripts/generate-catalog.cjs from the NuaSense API catalog.
// Do not edit by hand.

export interface DatasetEntry {
\tpath: string;
\ttitle: string;
\tgroup: string;
\tdescription: string;
\tfilters: string[];
}

export interface AnalysisEntry {
\tpath: string;
\tquestion: string;
\tparams: string[];
}

export const DATASETS: DatasetEntry[] = ${JSON.stringify(datasets, null, '\t')};

export const ANALYSES: AnalysisEntry[] = ${JSON.stringify(analyses, null, '\t')};
`;

const target = path.resolve(__dirname, '../nodes/NuaSense/catalog.ts');
if (process.argv.includes('--check')) {
	const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
	if (have !== out) {
		console.error('nodes/NuaSense/catalog.ts is stale: run node scripts/generate-catalog.cjs');
		process.exit(1);
	}
	console.log(`catalog.ts current: ${datasets.length} datasets, ${analyses.length} analyses`);
} else {
	fs.writeFileSync(target, out);
	console.log(`wrote catalog.ts: ${datasets.length} datasets, ${analyses.length} analyses`);
}
